/**
 * Returns video info for a given exercise name.
 * Falls back to a clean generated YouTube search tutorial if not explicitly listed.
 */
export function getVideoForExercise(exerciseName = "") {
  if (!exerciseName) return null;
  const cleanName = String(exerciseName).trim();
  const lower = cleanName.toLowerCase();

  // 1. Direct match
  if (EXERCISE_VIDEO_CATALOG[lower]) {
    return EXERCISE_VIDEO_CATALOG[lower];
  }

  // 2. Partial/key search
  for (const [key, item] of Object.entries(EXERCISE_VIDEO_CATALOG)) {
    if (lower.includes(key) || key.includes(lower)) {
      return item;
    }
    if (item.thName && (lower.includes(item.thName.toLowerCase()) || item.thName.toLowerCase().includes(lower))) {
      return item;
    }
  }

  // 3. Fallback video object
  return {
    name: cleanName,
    thName: cleanName,
    url: `https://www.youtube.com/results?search_query=${encodeURIComponent(cleanName + " exercise form tutorial")}`,
    targetMuscle: "กล้ามเนื้อที่เกี่ยวข้อง",
    difficulty: "ทั่วไป (All Levels)",
    description: `วิดีโอสาธิตและแนะนำฟอร์มการฝึกที่ถูกต้องสำหรับท่า ${cleanName}`,
    tips: "รักษาลำตัวให้มั่นคง หายใจเข้าจังหวะผ่อน หายใจออกจังหวะออกแรง เพื่อประสิทธิภาพและความปลอดภัย",
  };
}
